"""Tests for the regime taxonomy, with the look-ahead firewall as the centrepiece.

The firewall test exists because the oracle labeller is acausal on purpose. In a codebase
where eight structural defects all had the same shape -- an intention declared and nothing
checking it -- an "only for scoring" comment is not a control. These tests are the control.
"""

