def _daily(closes: list[float], *, start_run: int = 1) -> list[DailyBar]:
    """A contiguous run of synthetic daily bars with the given closes.

    Dates are generated by offsetting a base day, because the drawdown axis needs a
    180-day peak window and these series therefore run much longer than a month.
    """
    base = datetime(2022, 1, 1, tzinfo=UTC)
    bars: list[DailyBar] = []
    for index, close in enumerate(closes):
        bars.append(
            DailyBar(
                date=(base + timedelta(days=index)).strftime("%Y-%m-%d"),
                open_time_ms=index * 86_400_000,
                open=close,
                high=close * 1.01,
                low=close * 0.99,
                close=close,
                hours=24,
                contiguous_run=start_run + index,
            )
        )
    return bars


class TestLookAheadFirewall:
    """The causal path must not be able to reach the oracle, by signature or by call."""

    def test_the_causal_detector_does_not_accept_oracle_labels(self) -> None:
        parameters = set(inspect.signature(detect_regimes).parameters)
        assert parameters == {"daily", "params"}, (
            "detect_regimes gained an argument; if it is an oracle or a future-looking "
            "series, the study's central claim is void"
        )

    def test_no_function_on_the_causal_path_calls_the_oracle(self) -> None:
        for function in (detect_regimes, causal_features, classify, apply_persistence):
            source = inspect.getsource(function)
            assert "oracle" not in source.lower(), (
                f"{function.__name__} mentions the oracle; the causal path must not see it"
            )

    def test_causal_features_at_day_t_ignore_everything_after_t(self) -> None:
        rising = [100.0 * (1.01**index) for index in range(300)]
        truncated = causal_features(_daily(rising[:250]), RegimeParams())
        full = causal_features(_daily(rising), RegimeParams())
        for index in range(250):
            assert truncated[index] == full[index], (
                f"day {index} changed when later data was appended: look-ahead"
            )

    def test_the_oracle_by_contrast_does_change_with_future_data(self) -> None:
        """Confirms the oracle really is acausal, so the comparison above means something."""
        path = [100.0 * (1.01**index) for index in range(300)]
        short = oracle_regimes(_daily(path[:250]))
        long = oracle_regimes(_daily(path))
        assert short[:250] != long[:250]


