class TestMinimumDwellIsCausal:
    """The near-miss that produced this class: minimum duration must not read the future.

    `enforce_min_segment` decides whether a run was long enough by inspecting the whole
    series, which on day t means knowing how long the current run will END UP being. That
    is look-ahead. `apply_min_dwell` asks instead how long the standing label has ALREADY
    held, which only the past can answer. The first belongs to the oracle, the second to
    the detector, and swapping them silently flatters a backtest.
    """

    def test_dwell_at_day_t_is_unchanged_by_appending_future_days(self) -> None:
        labels: list[str | None] = ["ALCISTA"] * 40 + ["BAJISTA"] * 40
        short = apply_min_dwell(labels[:50], 30)  # type: ignore[arg-type]
        long = apply_min_dwell(labels, 30)  # type: ignore[arg-type]
        assert short == long[:50]

    def test_enforce_min_segment_by_contrast_does_read_the_future(self) -> None:
        labels: list[str | None] = ["ALCISTA"] * 40 + ["BAJISTA"] * 40
        short = enforce_min_segment(labels[:50], 30)  # type: ignore[arg-type]
        long = enforce_min_segment(labels, 30)  # type: ignore[arg-type]
        assert short != long[:50]

    def test_an_adopted_label_is_held_for_the_full_dwell_and_this_costs_lag(self) -> None:
        """The dwell does not suppress a blip, it LOCKS IT IN for min_days.

        That is the honest cost of the churn control and it is stated rather than hidden:
        a four-day challenger that gets through becomes a 30-day regime, which adds lag.
        `apply_persistence` is what filters blips; the dwell is what forbids short runs.
        """
        labels: list[str | None] = ["LATERAL"] * 40 + ["BAJISTA"] * 4 + ["LATERAL"] * 40
        settled = apply_min_dwell(labels, 30)  # type: ignore[arg-type]
        assert settled.count("BAJISTA") == 30

    def test_persistence_is_what_actually_filters_a_blip(self) -> None:
        """A challenger shorter than `persistence_days` never becomes the standing label."""
        labels: list[str | None] = ["LATERAL"] * 40 + ["BAJISTA"] * 4 + ["LATERAL"] * 40
        assert "BAJISTA" not in apply_persistence(labels, 5)  # type: ignore[arg-type]

    def test_a_challenger_that_reaches_the_threshold_is_adopted(self) -> None:
        labels: list[str | None] = ["LATERAL"] * 40 + ["BAJISTA"] * 5 + ["LATERAL"] * 40
        assert "BAJISTA" in apply_persistence(labels, 5)  # type: ignore[arg-type]

    def test_a_long_lived_challenger_does_replace_the_standing_label(self) -> None:
        labels: list[str | None] = ["LATERAL"] * 40 + ["BAJISTA"] * 40
        assert apply_min_dwell(labels, 30)[-1] == "BAJISTA"  # type: ignore[arg-type]

    def test_the_detector_never_emits_a_run_shorter_than_the_dwell(self) -> None:
        """The property the artifact violated: no 4-day 'regimes'."""
        path = [100.0 * (1.0 + 0.02 * math.sin(index / 9.0)) for index in range(500)]
        labels = detect_regimes(_daily(path), RegimeParams(min_regime_days=30))
        runs: list[int] = []
        current = 1
        for index in range(1, len(labels)):
            if labels[index] == labels[index - 1]:
                current += 1
            else:
                runs.append(current)
                current = 1
        interior = runs[1:]  # The first run includes the unlabelled warmup.
        assert all(length >= 30 for length in interior), interior


class TestDrawdownAxis:
    def test_a_window_ending_at_its_peak_has_no_drawdown(self) -> None:
        assert drawdown_from_peak([1.0, 2.0, 3.0]) == 0.0

    def test_drawdown_is_measured_from_the_highest_close(self) -> None:
        assert drawdown_from_peak([100.0, 200.0, 150.0]) == 0.25

    def test_the_bear_is_tested_before_the_residual_buckets(self) -> None:
        """Defect from iteration 1: the losing regime must not hide in a leftover bucket."""
        features = RegimeFeatures(
            date="2022-06-01",
            close=20000.0,
            efficiency=0.1,
            window_return=-0.5,
            volatility=0.05,
            volatility_rank=0.95,
            drawdown=0.55,
            price_over_ma=-0.30,
        )
        assert classify(features, RegimeParams(direction_axis="drawdown")) == "BAJISTA"
