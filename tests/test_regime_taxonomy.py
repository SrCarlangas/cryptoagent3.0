class TestClassification:
    def test_a_sustained_rise_is_labelled_bullish(self) -> None:
        labels = detect_regimes(_daily([100.0 * (1.012**index) for index in range(260)]))
        assert labels[-1] == "ALCISTA"

    def test_a_sustained_fall_is_labelled_bearish(self) -> None:
        labels = detect_regimes(_daily([100.0 * (0.988**index) for index in range(260)]))
        assert labels[-1] == "BAJISTA"

    def test_a_calm_market_pinned_at_its_peak_is_bullish_not_sideways(self) -> None:
        """Documents what the drawdown axis actually claims, which is not obvious.

        ALCISTA means "above trend and within 10% of the running peak". A market going
        nowhere AT its highs satisfies that, so it is bullish by this definition, not
        sideways. LATERAL is therefore NOT "a flat market": it is the calm bucket that sits
        in a mild pullback BELOW the peak. Naming it wrongly in a report would misdescribe
        the only regime that meets the success criterion.
        """
        path = [100.0 + 0.5 * math.sin(index / 2.0) for index in range(260)]
        assert detect_regimes(_daily(path))[-1] == "ALCISTA"

    def test_lateral_is_the_calm_bucket_below_the_peak(self) -> None:
        features = RegimeFeatures(
            date="2023-03-01",
            close=100.0,
            efficiency=0.1,
            window_return=0.0,
            volatility=0.01,
            volatility_rank=0.20,
            drawdown=0.15,
            price_over_ma=-0.02,
        )
        assert classify(features, RegimeParams(direction_axis="drawdown")) == "LATERAL"

    def test_warmup_is_unlabelled_rather_than_guessed(self) -> None:
        labels = detect_regimes(_daily([100.0 * (1.01**index) for index in range(40)]))
        assert labels[0] is None

    def test_a_lookback_spanning_many_absent_days_withholds_the_label(self) -> None:
        """Coverage, not an unbroken streak, is what decides. A real hole still abstains."""
        bars = _daily([100.0 * (1.01**index) for index in range(260)])
        # Drop 40 consecutive calendar days from the middle: the 180-day lookback now
        # stretches across far more calendar time than it has bars for.
        holed = [*bars[:120], *bars[160:]]
        features = causal_features(holed, RegimeParams())
        assert classify(features[185], RegimeParams()) is None

    def test_a_single_missing_day_does_not_erase_the_history(self) -> None:
        """The defect this guards: one absent day used to withhold the next six months.

        An unbroken-streak rule deleted 723 days -- all of 2020 and 2021 -- because the
        dataset has a handful of 1-5 hour gaps. The conclusion drawn from that ("LATERAL
        never occurs in 2020-2022") was a statement about the instrument, not the market.
        """
        bars = _daily([100.0 * (1.01**index) for index in range(300)])
        holed = [*bars[:100], *bars[101:]]  # exactly one calendar day missing
        features = causal_features(holed, RegimeParams())
        assert classify(features[250], RegimeParams()) is not None


class TestPersistence:
    def test_a_single_dissenting_day_cannot_flip_the_label(self) -> None:
        standing: list[str | None] = ["ALCISTA"] * 10 + ["BAJISTA"] + ["ALCISTA"] * 10
        settled = apply_persistence(standing, 5)  # type: ignore[arg-type]
        assert set(settled) == {"ALCISTA"}

    def test_a_sustained_challenger_does_flip_it(self) -> None:
        standing: list[str | None] = ["ALCISTA"] * 10 + ["BAJISTA"] * 10
        settled = apply_persistence(standing, 5)  # type: ignore[arg-type]
        assert settled[-1] == "BAJISTA"

    def test_persistence_costs_exactly_the_days_it_demands(self) -> None:
        """Five means five: adoption lands on the fifth consecutive challenger day."""
        standing: list[str | None] = ["ALCISTA"] * 10 + ["BAJISTA"] * 10
        settled = apply_persistence(standing, 5)  # type: ignore[arg-type]
        assert settled[14] == "BAJISTA"
        assert settled[13] == "ALCISTA"

    def test_disabling_persistence_passes_labels_through(self) -> None:
        standing: list[str | None] = ["ALCISTA", "BAJISTA", "ALCISTA"]
        assert apply_persistence(standing, 1) == standing  # type: ignore[arg-type]


class TestDetectionScoring:
    def test_a_perfect_detector_has_no_lag_and_no_false_alarms(self) -> None:
        labels: list[str | None] = ["ALCISTA"] * 20 + ["BAJISTA"] * 20
        quality = score_detection(labels, labels)  # type: ignore[arg-type]
        assert quality.median_lag_days == 0.0
        assert quality.false_alarms == 0
        assert quality.coverage == 1.0

    def test_a_late_detector_reports_its_lag(self) -> None:
        oracle: list[str | None] = ["ALCISTA"] * 20 + ["BAJISTA"] * 20
        late: list[str | None] = ["ALCISTA"] * 27 + ["BAJISTA"] * 13
        quality = score_detection(late, oracle)  # type: ignore[arg-type]
        assert quality.median_lag_days == 7.0

    def test_switching_to_the_wrong_regime_is_not_scored_as_a_detection(self) -> None:
        oracle: list[str | None] = ["ALCISTA"] * 20 + ["BAJISTA"] * 20
        wrong: list[str | None] = ["ALCISTA"] * 20 + ["LATERAL"] * 20
        quality = score_detection(wrong, oracle)  # type: ignore[arg-type]
        assert quality.matched == 0
        assert quality.missed == 1
        assert quality.false_alarms == 1

    def test_transitions_ignore_the_first_label_and_the_nones(self) -> None:
        labels: list[str | None] = [None, None, "LATERAL", "LATERAL", "ALCISTA"]
        assert transitions(labels) == [(4, "ALCISTA")]  # type: ignore[arg-type]


